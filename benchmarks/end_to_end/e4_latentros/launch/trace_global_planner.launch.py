"""
Benchmark: PoseStamped -> Path  (NavFn A* — simple wrapper)
Kernel:    navfn_benchmark_node  (topic-driven, no lifecycle/action)
Session:   e4_global_planner

Flow:
  rosbag /goal_pose → PoseStampedInputComponent
    → /robotperf/benchmark/goal_pose → navfn_benchmark_node (A*)
    → /global_plan → PathOutputComponent

6-tracepoint chain:
  pose_stamped_input_cb_init/fini → msg_received_1 → msg_published_1
    → path_output_cb_init/fini
"""
import os
from ament_index_python.packages import get_package_share_directory
from launch import LaunchDescription
from launch.actions import ExecuteProcess, SetEnvironmentVariable, TimerAction
from launch_ros.actions import ComposableNodeContainer, Node
from launch_ros.descriptions import ComposableNode
from tracetools_launch.action import Trace
from tracetools_trace.tools.names import DEFAULT_EVENTS_ROS

ROSBAG = '/tmp/benchmark_ws/src/rosbags/end_to_end/rosbag2_end_to_end_1m'


def generate_launch_description():
    go2_share = get_package_share_directory('go2_config')
    map_yaml = os.path.join(go2_share, 'maps_manual', 'square_map', 'square_map.yaml')

    trace = Trace(
        session_name='e4_global_planner',
        events_ust=['robotperf_benchmarks:*', 'ros2:*'] + DEFAULT_EVENTS_ROS,
        context_fields={
            'kernel': [],
            'userspace': ['vpid', 'vtid', 'procname'],
        },
    )

    # No rosbag needed — goals generated by goal_pose_publisher.py
    # Map comes from map_server

    input_component = ComposableNode(
        package='e4_latentros',
        namespace='robotperf',
        plugin='robotperf::planning::PoseStampedInputComponent',
        name='pose_stamped_input_component',
        parameters=[{
            'source_topic_name': '/goal_pose',
            'input_topic_name': '/robotperf/benchmark/goal_pose',
        }],
        extra_arguments=[{'use_intra_process_comms': False}],
    )

    output_component = ComposableNode(
        package='e4_latentros',
        namespace='robotperf',
        plugin='robotperf::planning::PathOutputComponent',
        name='path_output_component',
        parameters=[{'output_topic_name': '/global_plan'}],
        extra_arguments=[{'use_intra_process_comms': False}],
    )

    container = ComposableNodeContainer(
        name='benchmark_container',
        namespace='',
        package='rclcpp_components',
        executable='component_container_mt',
        composable_node_descriptions=[input_component, output_component],
        output='screen',
    )

    # Map server (lifecycle node — needs configure + activate)
    map_server = Node(
        package='nav2_map_server',
        executable='map_server',
        name='map_server',
        output='screen',
        parameters=[{'yaml_filename': map_yaml, 'use_sim_time': False}],
    )

    # Lifecycle transitions with delays for sequencing
    configure_map = TimerAction(
        period=2.0,
        actions=[ExecuteProcess(
            cmd=['ros2', 'lifecycle', 'set', 'map_server', 'configure'],
            output='screen',
        )],
    )
    activate_map = TimerAction(
        period=4.0,
        actions=[ExecuteProcess(
            cmd=['ros2', 'lifecycle', 'set', 'map_server', 'activate'],
            output='screen',
        )],
    )

    # Kernel: simple NavFn wrapper (regular node, event-driven, no lifecycle)
    kernel = Node(
        package='e4_latentros',
        executable='navfn_benchmark_node',
        output='screen',
    )

    # Disable CycloneDDS shared memory
    disable_cyclone_shm = SetEnvironmentVariable(
        'CYCLONEDDS_URI',
        '<CycloneDDS><Domain>'
        '<SharedMemory><Enable>false</Enable></SharedMemory>'
        '</Domain></CycloneDDS>'
    )

    # Goal publisher at 10Hz — starts after map loads (6s delay)
    goal_publisher = TimerAction(period=6.0, actions=[Node(
        package='e4_latentros',
        executable='goal_pose_publisher.py',
        name='goal_pose_publisher',
        output='screen',
        parameters=[{'rate': 10.0, 'goal_x': 2.0, 'goal_y': 0.0}],
    )])

    return LaunchDescription([disable_cyclone_shm,
        trace, container,
        map_server, configure_map, activate_map,
        kernel, goal_publisher,
    ])
